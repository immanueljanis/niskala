import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Turns the workspace's JSON sources of truth (packages/pools/pools.json, packages/abi/*.json) into
 * TypeScript modules under src/generated, so the SDK ships with the deployed addresses and typed ABIs
 * and needs no JSON import attributes at runtime. Run after `pnpm abi` or `pnpm deploy:pools`.
 */
const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");
const out = resolve(here, "../src/generated");
const header = "/* Generated by packages/sdk/scripts/gen.ts. Do not edit; run `pnpm --filter @niskala/sdk gen`. */\n";

const registry = JSON.parse(readFileSync(resolve(root, "packages/pools/pools.json"), "utf8"));
writeFileSync(resolve(out, "registry.ts"), `${header}export const registry = ${JSON.stringify(registry, null, 2)} as const;\n`);

for (const name of ["RfqMarket", "MockERC20"]) {
  const abi = JSON.parse(readFileSync(resolve(root, `packages/abi/${name}.json`), "utf8"));
  writeFileSync(resolve(out, `${name}.ts`), `${header}export const ${name}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`);
}
console.log("sdk: generated registry.ts, RfqMarket.ts, MockERC20.ts");
